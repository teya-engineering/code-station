import Foundation
import Testing
@testable import MenuBarApp

struct FileRoleTests {
    @Test func sortsGoFiles() {
        #expect(FileRole(path: "pkg/server/handler.go") == .code)
        #expect(FileRole(path: "pkg/server/handler_test.go") == .test)
        #expect(FileRole(path: "pkg/server/testdata/request.json") == .test)
        for path in ["api/v1/user.pb.go", "api/v1/user.pb.gw.go", "pkg/store/mock_store.go", "pkg/store/store_mock.go",
                     "pkg/store/mocks/store.go", "vendor/github.com/x/y/y.go", "go.sum"] {
            #expect(FileRole(path: path) == .generated, "\(path)")
        }
    }

    @Test func sortsJvmFiles() {
        #expect(FileRole(path: "src/main/java/com/acme/Payment.java") == .code)
        for path in ["src/test/java/com/acme/Helper.java", "src/integrationTest/kotlin/Flow.kt",
                     "src/testFixtures/java/Builder.java", "core/PaymentTest.java", "core/PaymentTests.java",
                     "core/PaymentIT.java", "core/PaymentTest.kt", "core/PaymentSpec.kt"] {
            #expect(FileRole(path: path) == .test, "\(path)")
        }
        for path in ["build/generated/source/Api.java", "app/target/generated-sources/Api.java",
                     "gradle.lockfile", "gradle/wrapper/gradle-wrapper.properties"] {
            #expect(FileRole(path: path) == .generated, "\(path)")
        }
    }

    @Test func sortsOtherFiles() {
        #expect(FileRole(path: "web/src/App.tsx") == .code)
        for path in ["web/src/App.test.tsx", "web/src/api.spec.js", "web/__tests__/App.tsx", "tools/test_parse.py",
                     "tools/parse_test.py", "conftest.py", "tests/unit/parse.py", "Tests/AppTests/Helper.swift",
                     "Sources/AppTests.swift", "web/__snapshots__/App.tsx.snap", "fixtures/user.json"] {
            #expect(FileRole(path: path) == .test, "\(path)")
        }
        for path in ["package-lock.json", "web/yarn.lock", "pnpm-lock.yaml", "Cargo.lock", "Package.resolved",
                     "poetry.lock", "Pipfile.lock", "Gemfile.lock", "composer.lock", "public/app.min.js",
                     "public/app.min.css", "web/dist/index.js", "web/node_modules/x/index.js"] {
            #expect(FileRole(path: path) == .generated, "\(path)")
        }
    }

    @Test func gitattributesBeatPathRules() async throws {
        let repo = try GitRepo()
        try repo.write(".gitattributes", "schema/*.go linguist-generated\nthird_party/** linguist-vendored\n")
        try repo.write("schema/types.go", "package schema")
        try repo.write("third_party/lib/lib_test.go", "package lib")

        let roles = await FileRole.roles(of: [change("schema/types.go"), change("third_party/lib/lib_test.go")],
                                         at: repo.path)

        #expect(roles["schema/types.go"] == .generated)
        #expect(roles["third_party/lib/lib_test.go"] == .generated)
    }

    @Test func generatedHeaderBeatsPathRules() async throws {
        let repo = try GitRepo()
        try repo.write("pkg/enum_string.go", "// Code generated by \"stringer -type=Enum\"; DO NOT EDIT.\n\npackage pkg\n")
        try repo.write("pkg/enum_test.go", "// Code generated by mockery. DO NOT EDIT.\n\npackage pkg\n")
        try repo.write("src/Api.java", "package api;\n\nimport javax.annotation.Generated;\n")
        try repo.write("src/Plain.java", "package api;\n")
        try repo.write("src/Modern.java", "package api;\n\nimport javax.annotation.processing.Generated;\n")
        try repo.write("tools/skip.go", "// Skips files marked @generated by tools.\npackage tools\n")

        let roles = await FileRole.roles(of: ["pkg/enum_string.go", "pkg/enum_test.go", "src/Api.java", "src/Plain.java",
                                              "src/Modern.java", "tools/skip.go"].map(change), at: repo.path)

        #expect(roles["pkg/enum_string.go"] == .generated)
        #expect(roles["pkg/enum_test.go"] == .generated)
        #expect(roles["src/Api.java"] == .generated)
        #expect(roles["src/Plain.java"] == .code)
        #expect(roles["src/Modern.java"] == .generated)
        #expect(roles["tools/skip.go"] == .code)
    }

    private func change(_ path: String) -> GitChange {
        GitChange(path: path, kind: .untracked, isStaged: false, isUnstaged: true, isBinary: false)
    }
}
